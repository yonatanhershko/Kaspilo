/**
 * Builds apps/mobile/src/components/ui/penIcons.ts from the owner's hand-drawn icon set in
 * apps/mobile/assets/icons/pen/*.svg (24×24, stroke "currentColor"). Run after adding or
 * changing an icon:  node scripts/pen-icons.mjs
 */
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const dir = fileURLToPath(new URL('../apps/mobile/assets/icons/pen/', import.meta.url));
const out = fileURLToPath(new URL('../apps/mobile/src/components/ui/penIcons.ts', import.meta.url));

const entries = readdirSync(dir)
  .filter((f) => f.endsWith('.svg'))
  .sort()
  .map((file) => {
    const svg = readFileSync(dir + file, 'utf8').trim();
    if (!/viewBox="0 0 24 24"/.test(svg)) throw new Error(`${file}: viewBox must be 0 0 24 24`);
    const inner = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '');
    const xml = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24">${inner}</svg>`;
    return `  ${JSON.stringify(file.replace(/\.svg$/, ''))}: ${JSON.stringify(xml)},`;
  });

writeFileSync(
  out,
  `// Generated by scripts/pen-icons.mjs from apps/mobile/assets/icons/pen. Do not edit by hand.\n` +
    `export const penIcons = {\n${entries.join('\n')}\n} as const;\n\n` +
    `export type PenIconName = keyof typeof penIcons;\n`,
);
execFileSync('npx', ['prettier', '--write', out], { stdio: 'ignore' });
console.log(`pen icons: ${entries.length} written to ${out}`);
